#!/usr/bin/env node
/**
 * Bakes `data/raw/geoBoundaries-KEN-ADM0_simplified.geojson` into
 * `data/kenya-outline.generated.ts`.
 *
 *   node services/geo/scripts/build-outline.mjs      (or: npm run geo:build)
 *
 * The national outline, as lon/lat rings. The data explorer clips NASA's global
 * imagery to it, so a satellite layer shows Kenya and nothing else.
 *
 * Why the ADM0 release and not the union of the 47 counties: a union of
 * simplified polygons that only nearly share edges leaves slivers along every
 * internal border, and a clip path built from them would draw hairline gaps
 * across the country. ADM0 is one outline drawn as one outline.
 *
 * Kept in lon/lat rather than projected into MAP_FRAME like the counties,
 * because its consumer works in Web Mercator tile space and MAP_FRAME is a
 * different projection fitted to a different canvas.
 *
 * Plain Node ESM with no dependencies, for the same reason as
 * build-counties.mjs: regenerating committed data must not need `npm install`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const SERVICE_DIR = join(HERE, "..");
const REPO_DIR = join(SERVICE_DIR, "..", "..");
const RAW_PATH = join(SERVICE_DIR, "data", "raw", "geoBoundaries-KEN-ADM0_simplified.geojson");
const OUT_PATH = join(SERVICE_DIR, "data", "kenya-outline.generated.ts");

/**
 * No Douglas-Peucker pass, unlike build-counties.mjs, because measuring one
 * showed it buys nothing here. The source is geoBoundaries' already-simplified
 * release, and on it:
 *
 *   tolerance 0       -> 4186 points, 108 rings, 73.2KB
 *   tolerance 0.001   -> 3874 points, 105 rings, 67.9KB  (~110m budget)
 *   tolerance 0.002   -> 2359 points,  77 rings, 41.7KB
 *   tolerance 0.005   -> 1052 points,  26 rings, 19.0KB
 *
 * Every saving comes from deleting islands (Lake Victoria's and the Lamu
 * archipelago's), not from smoothing the mainland, and a clip that drops an
 * island blanks the imagery over it. 73KB of points is cheap; a missing
 * Lamu is not.
 */

/** Decimal places kept: 4 is ~11m, finer than the source's own simplification. */
const PRECISION = 4;

/** A closed ring needs at least a triangle plus its closing point. */
const MIN_RING_POINTS = 4;

/** Kenya's extent, as a sanity bound: a refresh landing elsewhere fails here. */
const EXPECTED_EXTENT = { west: 33.5, south: -5.0, east: 42.0, north: 5.5 };

const round = (n) => Number(n.toFixed(PRECISION));

const raw = JSON.parse(readFileSync(RAW_PATH, "utf8"));
if (raw.features?.length !== 1) {
  throw new Error(`expected one ADM0 feature, found ${raw.features?.length}`);
}
const [feature] = raw.features;
if (feature.properties.shapeISO !== "KEN") {
  throw new Error(`expected Kenya (KEN), found ${feature.properties.shapeISO}`);
}
const geometry = feature.geometry;
const polygons =
  geometry.type === "MultiPolygon"
    ? geometry.coordinates
    : geometry.type === "Polygon"
      ? [geometry.coordinates]
      : null;
if (polygons === null) throw new Error(`unexpected geometry ${geometry.type}`);

let pointsIn = 0;
let dropped = 0;
/** Every ring, outer and hole alike: the consumer fills with the even-odd rule. */
const rings = [];
for (const polygon of polygons) {
  for (const ring of polygon) {
    pointsIn += ring.length;
    const simplified = ring.map(([lon, lat]) => [round(lon), round(lat)]);
    // Rounding can fold neighbours onto one point; drop the repeats.
    const deduped = simplified.filter(
      (p, i) => i === 0 || p[0] !== simplified[i - 1][0] || p[1] !== simplified[i - 1][1],
    );
    if (deduped.length < MIN_RING_POINTS) {
      dropped++;
      continue;
    }
    rings.push(deduped);
  }
}

let west = Infinity;
let south = Infinity;
let east = -Infinity;
let north = -Infinity;
for (const ring of rings) {
  for (const [lon, lat] of ring) {
    west = Math.min(west, lon);
    east = Math.max(east, lon);
    south = Math.min(south, lat);
    north = Math.max(north, lat);
  }
}
if (
  west < EXPECTED_EXTENT.west ||
  south < EXPECTED_EXTENT.south ||
  east > EXPECTED_EXTENT.east ||
  north > EXPECTED_EXTENT.north
) {
  throw new Error(`outline extent ${[west, south, east, north]} is not Kenya's`);
}

const pointsOut = rings.reduce((sum, ring) => sum + ring.length, 0);
const source = relative(REPO_DIR, RAW_PATH);
const script = relative(REPO_DIR, fileURLToPath(import.meta.url));
const out = `/**
 * GENERATED FILE. DO NOT EDIT BY HAND.
 *
 * Generated by  ${script}
 * From          ${source}
 * Regenerate    npm run geo:build
 *
 * Kenya's national outline (ADM0), published via geoBoundaries
 * ${feature.properties.shapeID} (gbOpen). License: Public Domain.
 * See ./README.md for the provenance record.
 *
 * Lon/lat (EPSG:4326) rings, rounded to ${PRECISION} decimals (~11m), not simplified:
 * ${pointsIn} points in, ${pointsOut} out, in ${rings.length} rings (${dropped} too small to keep).
 * Outer rings and holes are listed alike; fill them with the even-odd rule.
 */

/** \`[west, south, east, north]\` of every ring, in degrees. */
export const KENYA_OUTLINE_BBOX: readonly [number, number, number, number] = ${JSON.stringify([west, south, east, north])};

/** Every ring of the outline, each closed (first point repeated last). */
export const KENYA_OUTLINE: readonly (readonly (readonly [number, number])[])[] = ${JSON.stringify(rings)};
`;
writeFileSync(OUT_PATH, out);
console.log(
  `wrote ${relative(REPO_DIR, OUT_PATH)}: ${rings.length} rings, ${pointsIn} -> ${pointsOut} points, ${(out.length / 1024).toFixed(1)}KB`,
);
